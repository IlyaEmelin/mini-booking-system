// Заглушка для спецификатора `server-only` вне сборки Next.js (NFR-6).
//
// Серверные модули (`app/lib/db.ts`, `app/lib/password.ts` и следующие за ними)
// начинаются с `import "server-only"`. В сборке Next.js этот спецификатор
// разрешает сам Next.js: серверный граф получает пустой модуль, а клиентский —
// модуль, который бросает `You're importing a module that depends on "server-only"
// into a React Client Component module`, поэтому маркер реально держит границу
// «серверное не попадает в клиент».
//
// Команды вне сборки работают иначе: `tsx` (`npm run db:seed`,
// `npm run sessions:cleanup`, `npm test`) резолвит спецификатор сам, без алиасов
// Next.js, и падал бы с `MODULE_NOT_FOUND`. Пакета `server-only` в проекте нет, а
// добавлять зависимости нельзя (NFR-9, CR-26), поэтому запись `server-only` в
// `paths` файла `tsconfig.json` приводит спецификатор к этому пустому модулю.
//
// Запись действует только на инструменты: приложение, Server Components и Server
// Actions компилирует Turbopack, и его собственный алиас имеет приоритет над
// `paths` — проверено на Next.js 16.4.1 (клиентская сборка падает и при
// включённой записи), поэтому защита NFR-6 не ослабляется.
//
// `export {}` делает файл модулем при включённом `isolatedModules`; иначе
// TypeScript считает его глобальным скриптом и сообщает TS1208.

